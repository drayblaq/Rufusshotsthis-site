import type { Metadata, Viewport } from "next";
import { Analytics } from "@vercel/analytics/next";
import { SpeedInsights } from "@vercel/speed-insights/next";
import { Cormorant_Garamond, Jost } from "next/font/google";
import { site } from "@/content/site";
import { siteUrl } from "@/lib/site-url";
import "./globals.css";

/*
 * Fonts: self-hosted by next/font (no runtime request to Google), display: swap.
 * Both are VARIABLE fonts: one file per font covers every weight used
 * (Jost 500-800, Cormorant 500-600). Listing static weights would download one file
 * per weight, so variable is the lightest option.
 * - Cormorant Garamond (display): a high-contrast Garamond with hairline strokes that
 *   echo the fine pen strokes of the script logo. Elegant at heading sizes.
 * - Jost (body/UI): a clean geometric sans close to the "PHOTOGRAPHY" lettering
 *   under the logo, so text and logo feel like one family. Very legible on phones.
 */
const display = Cormorant_Garamond({
  variable: "--font-display",
  subsets: ["latin"],
  display: "swap",
});

const sans = Jost({
  variable: "--font-sans",
  subsets: ["latin"],
  display: "swap",
});

// Icons + social preview image come from app/ file conventions
// (favicon.ico, icon.png, apple-icon.png, opengraph-image.png, generated by npm run logos).
export const metadata: Metadata = {
  // Base for absolute URLs (social preview image etc.). See lib/site-url.ts.
  metadataBase: new URL(siteUrl()),
  title: { default: site.name, template: `%s · ${site.shortName}` },
  description: site.description,
  openGraph: { siteName: site.name, locale: "en_NG", type: "website" },
};

const isLiveSite = process.env.VERCEL_ENV === "production";

export const viewport: Viewport = {
  themeColor: "#faf8f5",
  // Lets env(safe-area-inset-*) report real values on notched phones.
  viewportFit: "cover",
};

/** Root layout: fonts + global styles. Header/footer live in app/(site)/layout.tsx. */
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${display.variable} ${sans.variable} h-full antialiased`}
    >
      <body className="flex min-h-full flex-col">
        {children}
        {/* Vercel Web Analytics + Speed Insights: live production site only, so local
            builds and preview deployments never load the scripts or skew the numbers. */}
        {isLiveSite && (
          <>
            <Analytics />
            <SpeedInsights />
          </>
        )}
      </body>
    </html>
  );
}
