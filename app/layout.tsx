import type { Metadata, Viewport } from "next";
import { Cormorant_Garamond, Jost } from "next/font/google";
import { site } from "@/content/site";
import "./globals.css";

/*
 * Fonts (both variable = one small file each, self-hosted by next/font, no runtime
 * request to Google):
 * - Cormorant Garamond (display): a high-contrast Garamond with hairline strokes that
 *   echo the fine pen strokes of the script logo. Elegant at heading sizes.
 * - Jost (body/UI): a clean geometric sans close to the "PHOTOGRAPHY" lettering
 *   under the logo, so text and logo feel like one family. Very legible on phones.
 */
const display = Cormorant_Garamond({
  variable: "--font-display",
  subsets: ["latin"],
  display: "swap",
});

const sans = Jost({
  variable: "--font-sans",
  subsets: ["latin"],
  display: "swap",
});

// Icons + social preview image come from app/ file conventions
// (favicon.ico, icon.png, apple-icon.png, opengraph-image.png, generated by npm run logos).
export const metadata: Metadata = {
  title: { default: site.name, template: `%s · ${site.shortName}` },
  description: site.description,
  openGraph: { siteName: site.name, locale: "en_NG", type: "website" },
};

export const viewport: Viewport = {
  themeColor: "#faf8f5",
  // Lets env(safe-area-inset-*) report real values on notched phones.
  viewportFit: "cover",
};

/** Root layout: fonts + global styles. Header/footer live in app/(site)/layout.tsx. */
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      className={`${display.variable} ${sans.variable} h-full antialiased`}
    >
      <body className="flex min-h-full flex-col">{children}</body>
    </html>
  );
}
